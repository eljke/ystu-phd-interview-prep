export function createOrderingQuestion(topic: Topic): OrderingQuestion | null {
  const card = cardsByTopicCode[topic.code];
  if (!card) return null;
  const id = `${topic.id}:order`;
  const items = card.items.map((text, index) => ({ id: `${id}:${index + 1}`, text }));
  return {
    id,
    type: 'ordering',
    prompt: card.prompt,
    explanation: card.explanation,
    keyPointIds: topic.keyPoints.map((point) => point.id),
    items,
    correctOrder: items.map((item) => item.id),
  };
}
