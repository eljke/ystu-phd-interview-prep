export function createTermQuestion(topic: Topic): FillBlankQuestion | null {
  const acceptedAnswers = answersByTopicCode[topic.code];
  if (!acceptedAnswers) return null;
  const keyPoint = topic.keyPoints[0]!;
  return {
    id: `${topic.id}:term`,
    type: 'fill-blank',
    prompt: `Назовите термин или короткое словосочетание: ${keyPoint.explanation}`,
    explanation: `Короткий ответ: ${acceptedAnswers[0]}.`,
    keyPointIds: [keyPoint.id],
    acceptedAnswers,
    caseSensitive: false,
  };
}
